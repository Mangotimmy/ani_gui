export function getSavedLanguage() {
  try {
    const saved = localStorage.getItem('aniflix_lang');
    if (saved && translations[saved]) {
      return saved;
    }
  } catch (e) {
    // fallback
  }
  return 'zh-TW'; // Default to Traditional Chinese TW/HK as requested
}

export function saveLanguage(langCode) {
  try {
    localStorage.setItem('aniflix_lang', langCode);
  } catch (e) {}
}

export function createTranslator(langCode = 'zh-TW') {
  const dict = translations[langCode] || translations['zh-TW'] || translations['en'];
  return function t(key, fallback = '') {
    return dict[key] || translations['en'][key] || fallback || key;
  };
}
